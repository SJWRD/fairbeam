import assert from 'node:assert/strict';
import {build} from 'vite';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url)).replaceAll('\\','/');
const built=await build({root,configFile:false,logLevel:'silent',resolve:{conditions:['browser']},build:{write:false,minify:false,lib:{entry:root+'src/lib/nativeDocuments.ts',formats:['es']}}});
globalThis.localStorage={getItem:()=>null,setItem(){},removeItem(){}};
const code=(Array.isArray(built)?built[0]:built).output[0].code;
const native=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const file=(id,scope='workspace')=>({id,file:id+'.design.json',design:{model:{id,name:id}},hash:'workspace-old',backup_scope:scope,readonly:false});
const response=(f,path,handle)=>({status:'saved',file:f,path,handle,document:{id:'uuid',path,revision:'external-sha',results_directory:'Project.results'},results:[],warnings:[]});
let calls=[],result;
globalThis.window={__TAURI_INTERNALS__:{invoke:(command,args)=>{calls.push({command,args});return typeof result==='function'?result():Promise.resolve(result);}}};
const original=file('one');
result=response(original,'C:/Chosen/One.fb','native-grant');
await native.persistNativeDocument(original,'workspace-new',false);
assert.deepEqual(calls[0],{command:'native_document_save',args:{request:{handle:undefined,modelId:'one',workspaceHash:'workspace-new',saveAs:false,suggestedName:'one.fb'}}});
assert.equal(native.nativeDocumentFor(original).handle,'native-grant');
assert.equal(native.nativeDocumentFor(file('one','other-workspace')),undefined);
result={status:'canceled'};
await assert.rejects(native.persistNativeDocument(original,'workspace-newer',false),/cancel/i);
assert.equal(native.nativeDocumentFor(original).handle,'native-grant','cancel does not retire the existing grant');
let finish;result=()=>new Promise(resolve=>finish=resolve);
const delayed=native.persistNativeDocument(original,'snapshot',false);
native.rememberNativeDocument(response(original,'D:/New selection/One.fb','new-grant'));
finish(response(original,'C:/Chosen/One.fb','old-grant'));
await delayed;
assert.equal(native.nativeDocumentFor(original).handle,'new-grant','old save cannot retarget a newer selection');
const copy=file('independent');result=response(copy,'C:/Chosen/Copy.fb','copy-grant');
assert.equal((await native.persistNativeDocument(original,'snapshot',true)).file,copy);
assert.equal(native.nativeDocumentFor(copy).handle,'copy-grant');
assert.equal(native.nativeDocumentFor(original).handle,'new-grant');
result=null;await native.pendingNativeDocument(['cancelled-handle']);
assert.deepEqual(calls.at(-1),{command:'native_document_next_open',args:{exclude:['cancelled-handle']}});
result={status:'import',name:'Legacy.json',content:'{}'};
assert.deepEqual(await native.pickNativeDocument(),result);
const reloaded=file('reload');
result={...response({id:reloaded.id,backup_scope:reloaded.backup_scope},'C:/Chosen/Reload.fb','reload-grant')};
await native.restoreNativeDocumentBinding(reloaded);
assert.deepEqual(calls.at(-1),{command:'native_document_restore',args:{modelId:'reload'}});
assert.equal(native.nativeDocumentFor(reloaded).handle,'reload-grant');
assert.equal(reloaded.hash,'workspace-old','restoration never hydrates cached workspace contents');
assert.equal(native.nativeDocumentFor(file('reload','other-workspace')),undefined);
await native.restoreNativeDocumentBinding(file('reload','other-workspace'));
assert.equal(native.nativeDocumentFor(file('reload','other-workspace')),undefined,'foreign workspace grant refused');
const delayedFile=file('delayed-restore');result=()=>new Promise(resolve=>finish=resolve);
const restoration=native.restoreNativeDocumentBinding(delayedFile);
native.rememberNativeDocument(response(delayedFile,'D:/New.fb','new-selection'));
finish(response(delayedFile,'C:/Old.fb','old-selection'));await restoration;
assert.equal(native.nativeDocumentFor(delayedFile).handle,'new-selection','late restoration cannot retarget newer Open');
result=null;await native.restoreNativeDocumentBinding(file('unknown'));
assert.equal(native.nativeDocumentFor(file('unknown')),undefined);
result=()=>Promise.reject({status:409,error:'changed on disk'});
await assert.rejects(native.persistNativeDocument(original,'snapshot',false),/changed on disk/);
delete globalThis.window;
assert.equal(native.nativeDocumentsAvailable(),false);
assert.equal(await native.persistNativeDocument(original,'snapshot',false),undefined);
console.log('Native documents: opaque grant payload, scope isolation, cancellation, stale binding, independent Save As, queue exclusions, JSON import and browser fallback pass');
