import assert from 'node:assert/strict';
import {createDocumentResultAutosave} from '../src/lib/documentResultAutosave.ts';
const file={id:'patch',hash:'saved-hash',backup_scope:'workspace',design:{name:'saved'}};
let release, calls=[], busy=[], errors=[];
const auto=createDocumentResultAutosave({persist:async f=>{calls.push(f);await new Promise(r=>release=r)},busy:v=>busy.push(v),failed:(f,e)=>errors.push([f,e])});
await auto(file,'[]',false,true);
await auto(file,'[1]',true,true);
await auto(file,'[1]',false,false);
assert.equal(calls.length,0);
const first=auto(file,'[1]',false,true);
await auto(file,'[2]',false,true);
assert.equal(calls.length,1,'no overlapping save');
assert.equal(calls[0],file,'uses saved file, not a live draft');
release();await first;
await auto(file,'[1]',false,true);
assert.equal(calls.length,1,'one attempt per completion token');
const second=auto(file,'[2]',false,true);release();await second;
assert.equal(calls.length,2,'later completion is not lost');
assert.deepEqual(busy,[true,false,true,false]);
let attempts=0;
const fail=createDocumentResultAutosave({persist:async()=>{attempts++;throw Error('disk full')},busy:()=>{},failed:(f,e)=>errors.push([f,e])});
await fail(file,'[1]',false,true);await fail(file,'[1]',false,true);
assert.equal(attempts,1,'failed disk operation does not loop');
assert.equal(errors.length,1);
await fail({...file,backup_scope:'another-workspace'},'[1]',false,true);
assert.equal(attempts,2,'ownership includes workspace');
console.log('Document result autosave: completion, serialization, saved snapshot, failure and ownership checks passed');
