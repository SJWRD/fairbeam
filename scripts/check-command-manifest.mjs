import assert from 'node:assert/strict';
import {readFileSync, readdirSync} from 'node:fs';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const uncomment = text => text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
function handlers(text) {
  return [...uncomment(text).matchAll(/generate_handler!\s*\[([^\]]*)\]/g)].flatMap(match =>
    match[1].split(',').map(value => value.trim()).filter(Boolean).map(value => {
      assert.match(value, /^(?:\w+::)*\w+$/, `Unsupported handler syntax: ${value}`);
      return value.split('::').at(-1);
    }));
}
function commands(text, pattern) {
  const match = uncomment(text).match(pattern);
  assert.ok(match, 'Command manifest declaration not found');
  return [...match[1].matchAll(/"([a-z0-9_]+)"/g)].map(value => value[1]);
}
function check(registered, declared, permissions, label) {
  assert.ok(registered.length, `${label}: no handlers found`);
  assert.equal(new Set(registered).size, registered.length, `${label}: duplicate handler`);
  assert.deepEqual([...registered].sort(), [...declared].sort(), `${label}: handler/manifest mismatch`);
  for (const command of registered) {
    assert.ok(permissions.includes(`allow-${command.replaceAll('_', '-')}`),
      `${label}: missing capability for ${command}`);
  }
}
const app = handlers(read('src-tauri/src/main.rs'));
const manifest = commands(read('src-tauri/build.rs'), /let\s+commands\s*=\s*&\[([\s\S]*?)\];/);
const viewer = JSON.parse(read('src-tauri/capabilities/viewer.json')).permissions;
const splash = JSON.parse(read('src-tauri/capabilities/default.json')).permissions;
check(app, manifest, [...viewer, ...splash], 'app');
const archivePermission = read('src-tauri/permissions/autogenerated/native_document_archive.toml');
assert.match(archivePermission, /identifier = "allow-native-document-archive"/);
assert.match(archivePermission, /commands\.allow = \["native_document_archive"\]/);
for (const command of app.filter(name => name.startsWith('native_document_'))) {
  assert.ok(viewer.includes(`allow-${command.replaceAll('_', '-')}`), `${command}: viewer permission missing`);
}
const account = handlers(read('src-tauri/src/account/plugin.rs'));
const accountManifest = commands(read('src-tauri/src/account/switch.rs'), /COMMANDS[^=]*=\s*&\[([\s\S]*?)\];/);
assert.deepEqual([...account].sort(), [...accountManifest].sort(), 'account plugin manifest mismatch');
// Any new command registry must be explicitly included in this check.
function scan(dir) {
  for (const entry of readdirSync(new URL(dir, root), {withFileTypes: true})) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) scan(path);
    else if (path.endsWith('.rs') && handlers(read(path)).length) {
      assert.ok(['src-tauri/src/main.rs', 'src-tauri/src/account/plugin.rs'].includes(path),
        `Add manifest coverage for ${path}`);
    }
  }
}
scan('src-tauri/src');
// Prove both halves of the original regression fail independently.
assert.throws(() => check(app, manifest.filter(x => x !== 'native_document_archive'), [...viewer, ...splash], 'missing manifest'));
assert.throws(() => check(app, manifest, [...viewer, ...splash].filter(x => x !== 'allow-native-document-archive'), 'missing permission'));
if (process.argv.includes('--built')) {
  const generated = JSON.parse(read('src-tauri/gen/schemas/acl-manifests.json'))['__app-acl__'].permissions;
  const capability = JSON.parse(read('src-tauri/gen/schemas/capabilities.json'))['viewer-capability'];
  for (const command of app) {
    const permission = `allow-${command.replaceAll('_', '-')}`;
    assert.deepEqual(generated[permission]?.commands.allow, [command], `Generated ACL missing ${command}`);
  }
  assert.ok(capability.permissions.includes('allow-native-document-archive'), 'Generated viewer ACL missing archive');
  assert.deepEqual(capability.windows, ['main']);
  assert.equal(capability.local, false);
  assert.deepEqual(capability.remote.urls, ['http://127.0.0.1:*/*']);
  console.log('Generated build ACL: archive permitted for the loopback main viewer; every app command has a generated permission');
}
console.log(`Command ACL: ${app.length} app and ${account.length} account handlers match manifests; viewer permissions and negative regressions passed`);
